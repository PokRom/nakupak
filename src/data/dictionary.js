const split = (raw) => Object.fromEntries(
  Object.entries(raw).map(([sectionId, list]) => [
    sectionId,
    list.split(',').map((s) => s.trim().replace(/\s+/g, ' ')).filter(Boolean),
  ])
);
const CS = split(RAW);
const EN = split(RAW_EN);

